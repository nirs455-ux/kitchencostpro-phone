// מחזיר אחוז ניצולת מוערך או null (אין מספר מאומת לשם הזה)
export function estimateYield(name) {
    const s = norm(name);
    if (!s) return null;
    for (const [re, pct, extra] of TABLE) {
        if (!re.test(s)) continue;
        const rest = s.replace(new RegExp(re.source, "gu"), " ").split(" ").filter(Boolean);
        if (rest.every((w) => STD.has(w) || (extra && extra.has(w)))) return pct;
        return null; // המוצר הספציפי (קפוא, חתוך, קלוף...) נראה אחרת: לא מנחשים
    }
    return null;
}

// מוצרים קיימים שאפשר למלא להם ניצולת מוערכת: ראשי, במשקל, לא קפוא, בלי ניצולת ובלי משקלי עיבוד, והשם בטבלה
export function planYieldFill(pantry) {
    const out = [];
    for (const r of pantry || []) {
        if (r.parent_id || r.unit_type !== "weight" || r.is_frozen || r.yield_est) continue;
        if (Number(r.yield_pct || 100) !== 100 || r.weight_before != null || r.weight_after != null) continue;
        const to = estimateYield(r.name);
        if (to) out.push({ id: r.id, name: r.name, from: 100, to });
    }
    return out.sort((a, b) => a.name.localeCompare(b.name, "he"));
}

// מוצרים שהניצולת שלהם עדיין הערכה (לא נשקלה בעיבוד): אפשר להחזיר ל-100
export const estimatedYieldItems = (pantry) => (pantry || []).filter((r) => r.yield_est && !r.parent_id);

// האם ניצולת המוצר חלה על שורת מתכון. prep: "proc" = מעובד (קילוף וניקוי), "raw" = בלי עיבוד, בלי ערך = ברירת מחדל:
// ניצולת המוצר, שנשקלה או מוערכת, חלה תמיד על שורה, אלא אם סימנו בה "בלי ניצולת"
export const yieldApplies = (row, prep) => prep !== "raw";
export const rowForLine = (row, prep) => (yieldApplies(row, prep) ? row : { ...row, yield_pct: 100 });
