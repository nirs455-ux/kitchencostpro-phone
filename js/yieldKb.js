const norm = (s) => String(s || "").toLowerCase().replace(/["'`׳״”“’]/g, "").replace(/[(),.\-\/\\|:;]/g, " ").replace(/\s+/g, " ").trim();
const W = (src) => new RegExp(`(?<![א-תa-z])(?:${src})(?![א-תa-z])`, "u");

// מילים שמותר להוסיף לכל שם בלי לשנות את המשמעות
