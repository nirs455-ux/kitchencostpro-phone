// מוצרים ללא עלות: מים וחומרים ממוחזרים. מחיר 0, לא נדרש מחיר, ולא מסומנים "ממתין למחיר".
// שם מים (מים, מים פושרים, מים חמים, קרח...) מסומן אוטומטית. כל מוצר אחר מסומן ידנית בכפתור "ללא עלות".
const WATER = /^(?:מים|קרח)(?: (?:פושרים|חמים|קרים|רותחים|רותחין|קרח|מהברז|מסוננים|קרירים|צוננים))?$/u;
export const isWaterName = (name) => WATER.test(String(name || "").replace(/["'`׳״]/g, "").replace(/[(),.\-\/\|:;]/g, " ").replace(/\s+/g, " ").trim());
export const isFreeItem = (row) => !!(row && row.free);
