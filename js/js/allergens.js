const NOT_MILK = ["חלבון", "חלבה", "חלווה", "חלב קוקוס", "חלב שקדים", "חלב סויה", "חלב שיבולת", "חלב אורז"];

// מחזיר מערך מפתחות אלרגנים מוצעים לפי השם. "חלב קוקוס"/"חלב שקדים" וכד' - ההצעה גסה, ולכן המשתמש חייב לבדוק.
export function suggestAllergens(name) {
    const n = String(name || "").trim().toLowerCase();
    if (!n) return [];
    const out = [];
    for (const [key, words] of Object.entries(KEYWORDS)) {
        if (words.some((w) => n.includes(w))) out.push(key);
    }
    // "חלבון" (ביצה/שרירי), חלבה, וחלב צמחי (קוקוס/שקדים/סויה/שיבולת/אורז) אינם חלב פרה
    if (NOT_MILK.some((w) => n.includes(w))) return out.filter((k) => k !== "milk");
    return out;
}

