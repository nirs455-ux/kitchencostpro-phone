const norm = (s) => String(s || "").toLowerCase().replace(/["'`׳״]/g, "").replace(/[\-–_.,()־/]/g, " ").replace(/\s+/g, " ").trim();
const KEYS = new Set(["gluten", "milk", "eggs", "peanuts", "tree_nuts", "sesame", "soy", "fish", "shellfish", "celery", "mustard", "sulfites", "lupin"]);

function parseResult(res) {
    const r = res.trim();
    if (r === "-") return { status: "free", keys: [], likely: [] };
    if (r.startsWith("?")) {
        const likely = r.includes(":") ? r.split(":")[1].split(",").map((x) => x.trim()).filter((k) => KEYS.has(k)) : [];
        return { status: "unknown", keys: [], likely };
    }
    const partial = r.endsWith("+");
    const keys = r.replace(/\+$/, "").split(",").map((x) => x.trim()).filter((k) => KEYS.has(k));
    return { status: partial ? "partial" : "known", keys, likely: [] };
}

// אינדקס: רשימת { tokens, result }. כל שם חלופי = רשומה.
const ENTRIES = [];
for (const line of LINES) {
    const [names, res] = line.split("::");
    const result = parseResult(res);
    for (const n of names.split("|")) {
        const tokens = norm(n).split(" ").filter(Boolean);
        if (tokens.length) ENTRIES.push({ tokens, alias: tokens.join(" "), result });
    }
}

// מחפש שם נקי במאגר. מחזיר { status, keys, likely } או null אם הרכיב לא מוכר.
// התאמה: כל מילות השם החלופי חייבות להופיע בשם. נבחר השם החלופי הספציפי ביותר (הכי הרבה מילים).
// אם כמה התאמות שוות בספציפיות נותנות תוצאות שונות - מחזירים "לא ידוע" (לא מנחשים).
export function lookupAllergenKb(name) {
    const words = norm(name).split(" ").filter(Boolean);
    if (!words.length) return null;
    const set = new Set(words);
    let best = [];
    let bestLen = 0;
    for (const e of ENTRIES) {
        if (!e.tokens.every((t) => set.has(t))) continue;
        if (e.tokens.length > bestLen) { best = [e]; bestLen = e.tokens.length; }
        else if (e.tokens.length === bestLen) best.push(e);
    }
    if (!best.length) return null;
    const marker = words.find((w) => COMPOSITE.has(w));
    if (marker && !best.some((e) => e.tokens.includes(marker))) return { status: "unknown", keys: [], likely: [] };
    const sig = (e) => JSON.stringify([e.result.status, e.result.keys, e.result.likely]);
    // כפילויות בכוונה (למשל שמן זית ברשימת "?" וגם ב"-"): מעדיפים את הרשומה המאוחרת, כלומר הספציפית יותר
    const lastBySig = new Map();
    for (const e of best) lastBySig.set(e.alias, e);
    const uniq = [...lastBySig.values()];
    const sigs = new Set(uniq.map(sig));
    if (sigs.size > 1) return { status: "unknown", keys: [], likely: [] };
    return { ...uniq[uniq.length - 1].result, via: uniq[uniq.length - 1].alias };
}

